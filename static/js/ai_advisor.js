window.addEventListener('DOMContentLoaded', () => {
  const ctx = document.getElementById('contextSelect');
  const q = document.getElementById('question');
  const btn = document.getElementById('askBtn');
  const loading = document.getElementById('aiLoading');
  const out = document.getElementById('aiResponse');

  function fallbackExplain(){
    // No demo/narrative placeholder content: provide a neutral failure message.
    out.innerHTML = `
      <div class="small text-muted">Unable to generate analysis right now. Ensure the backend endpoint /ai/explain is reachable and your Ollama server is running.</div>
      <div class="mt-2"><strong>Next steps:</strong> verify Ollama (env OLLAMA_BASE_URL), confirm the model in OLLAMA_MODEL, and retry.</div>
    `;
  }

  btn.addEventListener('click', async () => {
    loading.style.display = 'block';
    btn.disabled = true;
    out.textContent = '';

    const question = q.value.trim();
    const context = { mode: ctx ? ctx.value : undefined };

    try {
      // Wire to backend Ollama via Flask.
      const questionPayload = question + `\n\nQuery configuration:\n- Focus: limitations, risk, mitigations\n- Tone: executive\n- Output language: en\n`;

      const resp = await fetch('/ai/explain', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          question: questionPayload,
          context: {
            ...context,
            query_configuration: {
              model_style: 'llama3',
              tone: 'executive',
              output_language: 'en',
              focus: ['limitations', 'risk', 'mitigations'],
              max_bullets_per_section: 5
            }
          }
        })
      });


      if (!resp.ok) throw new Error(`HTTP ${resp.status}`);
      const data = await resp.json();
      const text = data.text;
      out.innerHTML = `<div class="small text-muted">Generated by local Ollama</div><div class="mt-2">${text.replaceAll('\n','<br/>')}</div>`;
    } catch (e) {
      fallbackExplain();
    }

    loading.style.display = 'none';
    btn.disabled = false;
  });

});

